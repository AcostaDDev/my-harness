@pytest.mark.parametrize('with_roadmap', [True, False])
def test_installed_cli_resolves_remapped_source_identities(installed, tmp_path, capsys, with_roadmap):
    db, _, root, plan = installed
    assert invoke(db, tmp_path / 'snapshots') == 0
    capsys.readouterr()
    before, originals = dump_rows(db), inventory(root)
    plan['files'] = [file for file in plan['files'] if file['role'] != 'decisions'
                     and (with_roadmap or file['role'] != 'roadmap')]
    plan['codes'] = {'P001': 'P002', 'P001-T001': 'P002-T001', 'P001-T002': 'P002-T001'}
    path = tmp_path / 'conversion.json'

    def convert(*args, status=0):
        path.write_text(json.dumps(plan))
        assert main(['knowledge-convert', '--database', str(db), '--root', str(root), '--plan', str(path), *args]) == status
        output = capsys.readouterr()
        return output.err if status else json.loads(output.out)

    def confirm(preview, *, status=0):
        return convert('--preview-sha256', preview['preview_sha256'], '--reason', 'Reviewed remapped codes', status=status)

    link = plan['links'][0]
    link['source'][-1] = 'P002-T001'
    blocked = convert()
    assert {'code': 'canonical_code_collision', 'kind': 'task', 'item': 'P002-T001',
            'sources': ['P001-T001', 'P001-T002'], 'blocking': True} in blocked['report']
    assert 'blocking choices' in confirm(blocked, status=1)
    assert dump_rows(db) == before

    del plan['codes']['P001-T002']
    canonical = convert()
    link['source'][-1] = 'P001-T001'
    shown = convert()
    assert canonical['links'] == shown['links']
    assert convert() == shown and not any(note.get('blocking') for note in shown['report'])
    members = {(item['kind'], item['code']): item for item in shown['members']}
    assert {code for kind, code in members if kind == 'phase'} == {'P002'}
    assert {code for kind, code in members if kind == 'task'} == {'P002-T001', 'P001-T002'}
    phase = members['phase', 'P002']
    task = members['task', 'P002-T001']
    assert phase['content']['title'] == ('First phase' if with_roadmap else 'P002')
    assert phase['content']['objective'] == 'Preserve evidence'
    assert phase['source']['reference'] == 'legacy-v2'
    assert task['content']['title'] == 'Convert'
    assert task['content']['problem'].strip() == '**Objective:** Preserve evidence.'
    assert task['content']['expected_result'] == 'Preserve evidence.'
    assert task['source'] == {'kind': 'legacy_document', 'path': 'docs/NEXT_STEPS.md', 'heading': 'P001-T001',
                              'reference': 'legacy-phase', 'sha256': hash_bytes(originals[Path('docs/NEXT_STEPS.md')])}
    if with_roadmap:
        assert any(note['code'] == 'phase_definition_precedence' and note['item'] == 'P002'
                   for note in shown['report'])
    expected = {('managed_phase', 'legacy-phase'): phase['item_id'],
                ('phase_task', 'P001-T001'): task['item_id'],
                ('phase_task', 'P001-T002'): members['task', 'P001-T002']['item_id']}
    assert len({(m['legacy_kind'], m['legacy_ref']) for m in shown['mapping']}) == len(shown['mapping'])
    assert expected.items() <= {(m['legacy_kind'], m['legacy_ref']): m['item_id'] for m in shown['mapping']}.items()

    result = confirm(shown)
    adopted = dump_rows(db)
    assert confirm(shown) == {**result, 'replayed': True}
    assert dump_rows(db) == adopted
    engine = make_engine(f'sqlite:///{db}')
    try:
        knowledge = KnowledgeRepository(engine)
        revision = knowledge.revision(result['project_id'])
        assert revision.number == 1
        assert revision.item('task', 'P002-T001').source == task['source']
        assert revision.item('task', 'P001-T001') is None and revision.item('phase', 'P001') is None
        assert {(link.kind, link.source, link.target) for link in revision.links} >= {
            ('part_of', task['item_id'], phase['item_id']),
            ('part_of', expected['phase_task', 'P001-T002'], phase['item_id']),
            ('addresses', task['item_id'], members['requirement', 'R001']['item_id']),
        }
        for (kind, ref), item_id in expected.items():
            assert knowledge.legacy(result['project_id'], kind, ref) == item_id
    finally:
        engine.dispose()
    with closing(sqlite3.connect(db)) as conn:
        assert conn.execute('SELECT legacy_kind, legacy_ref, item_id FROM knowledge_identity_map '
                            "WHERE legacy_kind IN ('managed_phase', 'phase_task') ORDER BY legacy_kind, legacy_ref"
                            ).fetchall() == [(*key, item_id) for key, item_id in sorted(expected.items())]
    assert all(adopted[table] == rows for table, rows in before.items() if rows)
    assert inventory(root) == originals


def test_portable_transfer_of_converted_knowledge_validates_mapped_references(installed, tmp_path):
    from my_harness.core.engine import knowledge as k, knowledge_documents as documents
    from my_harness.storage.work_language import associate
    from test_knowledge_documents import payload, run as exchange

