@pytest.mark.parametrize('failure', [None, 'bytes', 'inventory', 'accounting_digest', 'schema',
                                     'restore_marker', 'reference', 'wal'])
def test_0028_format3_upgrade_is_verified_and_leaves_original(installed, tmp_path, capsys, failure):
    _, bundle, _, _ = installed
    if failure == 'bytes':
        next((bundle / 'artifacts').iterdir()).write_bytes(b'tampered bytes')
    elif failure == 'inventory':
        seal(bundle, lambda m: m['accounting'].update(usage_valuations=0))
    elif failure == 'accounting_digest':
        with closing(sqlite3.connect(bundle / 'state.sqlite3')) as db, db:
            db.execute("UPDATE metrics_references SET content=content || ' ' WHERE kind='tariff'")
        reseal_database(bundle)
    elif failure == 'schema':
        with closing(sqlite3.connect(bundle / 'state.sqlite3')) as db, db:
            db.execute("UPDATE alembic_version SET version_num='0027_profile_proposals'")
        reseal_database(bundle)
    elif failure == 'restore_marker':
        with closing(sqlite3.connect(bundle / 'state.sqlite3')) as db:
            db.execute('PRAGMA user_version=0')
        reseal_database(bundle)
    elif failure == 'reference':
        seal(bundle, lambda m: m['files'][0].update(labels=['tampered']))
    elif failure == 'wal':
        (bundle / 'state.sqlite3-wal').write_bytes(b'not sealed')
    before = inventory(bundle)
    target = tmp_path / 'upgraded?copy'
    assert main(['backup-upgrade', str(bundle), str(target)]) == int(failure is not None)
    assert inventory(bundle) == before
    if failure:
        assert capsys.readouterr().err and not (target / 'COMPLETE').exists()
        if failure == 'restore_marker':
            assert not (target / 'state.sqlite3').exists()
        return
    manifest = verify_bundle(target)
    assert manifest['schema'] == SCHEMA_REVISION and manifest['accounting']['usage_valuations'] == 1
    assert manifest['upgraded_from']['schema'] == INSTALLED
    assert manifest['upgraded_from']['manifest_sha256'] == hash_bytes(before[Path('manifest.json')])
    assert manifest['files'] == json.loads((bundle / 'manifest.json').read_bytes())['files']
    original, upgraded = (dump_rows(directory / 'state.sqlite3') for directory in (bundle, target))
    assert {table: upgraded[table] for table in FROZEN} == {table: original[table] for table in FROZEN}
    restore_backup(target, tmp_path / 'restore')


