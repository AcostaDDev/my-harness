def hash_bytes(raw):
    return hashlib.sha256(raw).hexdigest()


def dump_rows(path):
    with closing(sqlite3.connect(path)) as db:
        tables = [row[0] for row in db.execute("SELECT name FROM sqlite_master WHERE type='table' ORDER BY name")]
        return {name: db.execute(f'SELECT * FROM "{name}" ORDER BY rowid').fetchall() for name in tables}


def inventory(directory):
    return {p.relative_to(directory): p.read_bytes() for p in directory.rglob('*') if p.is_file()}


def definitions(repository, root, documents):
    definition = {'code': 'P001', 'objective': 'Preserve evidence', 'tasks': ['P001-T001', 'P001-T002'],
                  'exit_criteria': ['Original bytes survive'], 'tag': 'p001', 'documents': sorted(documents)}
    with Session(repository.engine) as session, session.begin():
        phase = PhaseRow(id='legacy-phase', root=str(root), code='P001', definition=definition,
                         definition_sha256=digest(definition), documents=documents, definition_number=2,
                         status='READY_TO_CLOSE', version=4, created_at='before', updated_at='after')
        session.add(phase)
        session.flush()
        session.add_all([
            PhaseDefinitionRow(id=ident, phase_id=phase.id, number=number, definition=value,
                               definition_sha256=digest(value), documents=documents, origin=origin, created_at='now')
            for ident, number, value, origin in (
                ('legacy-v1', 1, {**definition, 'objective': 'Previous objective'}, 'created'),
                ('legacy-v2', 2, definition, 'amended'))
        ])


