        operations = DomainOperations(engine)
        preview = operations.convert_installed(str(root), plan)
        adopted = operations.convert_installed(
            str(root), plan, preview_sha256=preview['preview_sha256'], reason='Synthetic conversion')
        repo = KnowledgeRepository(engine)
        revision = repo.revision(adopted['project_id'])
        target = tmp_path / 'portable-destination'
        target.mkdir()
        destination = repo.project(str(target))
        with Session(engine) as session, session.begin():
            associate(session, root=str(target), project_id=destination, work_language='en', source='migration',
                      confirmation={'synthetic': True}, now='2026-11-09T00:00:00+00:00')
        portable = documents.portable(documents.snapshot(revision), 'en')
        body = {'files': {}, 'portable': portable, 'mode': 'new', 'choices': {}, 'acknowledged': [],
                'expected_revision_id': None}
        requirement = revision.item('requirement', 'R001').item_id
        excluded = {**body, 'choices': {requirement: {'action': 'exclude', 'target': '', 'code': ''}}}
        report = exchange(engine, target, 'documents.stage', payload(excluded), 'exclude')['report']
        excluded['acknowledged'] = [k.digest(note) for note in report if not note['blocking']]
        blocked = exchange(engine, target, 'documents.stage', payload(excluded), 'exclude-ack')
        assert blocked['draft_id'] is None and any(
            note.get('detail') == 'excluded_reference_requires_resolution' for note in blocked['report'])
        assert repo.head(destination) is None
        before = dump_rows(db)
        staged = exchange(engine, target, 'documents.stage', payload(body), 'portable')
        shown = exchange(engine, target, 'documents.preview', {'record_id': staged['record_id']})
        assert set(shown['mapping']) == set(revision.members)
